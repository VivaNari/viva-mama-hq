export async function migrate(): Promise<{ updated: number; missing: number }> {
    let updated = 0;
    let missing = 0;

    for (const [id, bundle] of Object.entries(HINDI_CONTENT)) {
        const res = await contentModel.updateOne(
            { _id: new mongoose.Types.ObjectId(id) },
            { $set: { "translations.hi": bundle } },
        );

        if (res.matchedCount === 0) {
            console.warn(`No content found for _id=${id}`);
            missing += 1;
        } else {
            updated += 1;
        }
    }

    console.log(`Done. Updated ${updated} article(s), ${missing} id(s) unmatched.`);
    return { updated, missing };
}
