export async function migrate(): Promise<{ updated: number; missing: number }> {
    let updated = 0;
    let missing = 0;

    for (const [key, bundle] of Object.entries(HINDI_RECOMMENDATIONS)) {
        const [phase, zone, category] = key.split("|");
        const res = await RecommendationModel.updateOne(
            { phase, zone, category },
            { $set: { "translations.hi": bundle } },
        );

        if (res.matchedCount === 0) {
            console.warn(`No recommendation found for ${key}`);
            missing += 1;
        } else {
            updated += 1;
        }
    }

    console.log(`Done. Updated ${updated} recommendation(s), ${missing} missing.`);
    return { updated, missing };
}
