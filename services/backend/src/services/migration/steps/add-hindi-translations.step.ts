export async function migrate(): Promise<void> {
    // 1) Resolve duplicate weekly-checkin-v1 docs: keep the one whose
    //    startNodeId === "intro" PUBLISHED, archive any other published ones.
    const weeklyDocs = await flowDefinitionModel
        .find({ slug: WEEKLY_CHECKIN_SLUG, status: "PUBLISHED" })
        .sort({ createdAt: 1 });

    let canonicalWeekly = weeklyDocs.find((d) => d.startNodeId === "intro");
    if (!canonicalWeekly && weeklyDocs.length) {
        // Fallback: newest published doc.
        canonicalWeekly = weeklyDocs[weeklyDocs.length - 1];
    }

    if (!canonicalWeekly) {
        console.warn(`No PUBLISHED "${WEEKLY_CHECKIN_SLUG}" found — skipping weekly check-in.`);
    } else {
        for (const doc of weeklyDocs) {
            if (doc._id.toString() !== canonicalWeekly._id.toString()) {
                await flowDefinitionModel.updateOne(
                    { _id: doc._id },
                    { $set: { status: "ARCHIVED" } },
                );
                console.log(`Archived duplicate weekly-checkin doc ${doc._id.toString()}`);
            }
        }

        await flowDefinitionModel.updateOne(
            { _id: canonicalWeekly._id },
            { $set: { "translations.hi": WEEKLY_CHECKIN_HI } },
        );
        console.log(
            `Added Hindi translations to weekly-checkin doc ${canonicalWeekly._id.toString()}`,
        );
    }

    // 2) Onboarding flow.
    const onboarding = await flowDefinitionModel
        .findOne({ slug: ONBOARDING_SLUG, status: "PUBLISHED" })
        .sort({ version: -1, createdAt: -1 });

    if (!onboarding) {
        console.warn(`No PUBLISHED "${ONBOARDING_SLUG}" found — skipping onboarding.`);
    } else {
        await flowDefinitionModel.updateOne(
            { _id: onboarding._id },
            { $set: { "translations.hi": ONBOARDING_HI } },
        );
        console.log(`Added Hindi translations to onboarding doc ${onboarding._id.toString()}`);
    }
}
