const log = createModuleLogger(logger, "chatbot-turn");

/** What else came with her message, beyond the text. */
export type TChatTurn = {
    /** Generated by the app; makes a retried POST harmless and keys the reply. */
    clientMessageId?: string | null;
    /** Files already claimed for this turn by the controller. */
    attachments?: IChatAttachment[];
    lang?: string | null;
};

type TQuota = { used: number; limit: number | null; remaining: number | null };

/** Answer verdicts that mean the file was accepted as a mother/baby health document. */
const ACCEPTED_VERDICT = "ANALYZED";

const toChatbotLang = (lang: string | null | undefined): "en" | "hi" =>
    String(lang ?? "")
        .toLowerCase()
        .startsWith("hi")
        ? "hi"
        : "en";

/** Marks an error whose turn has already been failed (refunded, reported). */
class HandledTurnError extends Error {
    constructor(public readonly cause: unknown) {
        super("Chatbot turn failed");
    }
}

class ChatFlowAIService extends BaseService<IFlowDefinition> {
    private userService: UserService;
    private messageService: MessageService;
    private llmService: LLMService;
    private chatLogProposalService: ChatLogProposalService;
    private expertService: ExpertService;

    constructor() {
        super(flowDefinitionModel);
        this.userService = new UserService();
        this.messageService = new MessageService();
        this.llmService = new LLMService();
        this.expertService = new ExpertService();
        this.chatLogProposalService = new ChatLogProposalService();
    }

    /**
     * Keep only the experts this user is actually allowed to be sent to.
     *
     * The chatbot pipeline mirrors our referral rule when it builds its prompt
     * directory, but this server owns that rule — so we re-check here rather than
     * trusting the mirror. A drift in the Python port then costs a missing button,
     * never a deep link to an expert she should not be seeing.
     */
    private resolveSuggestedExperts = async (
        userId: string,
        raw: unknown,
    ): Promise<ISuggestedExpert[]> => {
        if (!Array.isArray(raw) || raw.length === 0) {
            return [];
        }

        try {
            const visibleExperts = await this.expertService.getVisibleExperts(userId);
            const visibleById = new Map(
                visibleExperts.map((expert) => [String(expert._id), expert]),
            );

            return raw.reduce<ISuggestedExpert[]>((accepted, suggestion) => {
                const suggestedId = String((suggestion as { id?: unknown })?.id ?? "");
                const expert = visibleById.get(suggestedId);
                if (!expert) {
                    console.warn(
                        `Dropping expert suggestion ${suggestedId}: not visible to user ${userId}`,
                    );
                    return accepted;
                }

                // Names come from our own record, not from the model's prose.
                accepted.push({
                    expertId: expert._id as unknown as ISuggestedExpert["expertId"],
                    name: expert.name,
                    speciality: expert.speciality,
                });
                return accepted;
            }, []);
        } catch (error) {
            console.error("Failed to validate suggested experts:", error);
            return [];
        }
    };

    setSseConnection = (res: Response): void => {
        res.setHeader("Content-Type", "text/event-stream");
        res.setHeader("Cache-Control", "no-cache");
        res.setHeader("Connection", "keep-alive");
        res.flushHeaders();
    };

    initInstanceVariables = async ({ res }: { res: Response }): Promise<void> => {
        this.setSseConnection(res);
    };

    handleChatbotSSEConnection = async (
        userId: string,
        slug: string,
        flowType: FlowType,
        res: Response,
    ): Promise<void> => {
        try {
            console.log("slug", slug);
            await this.initInstanceVariables({ res });
            const userInstance: IUser | null = await this.userService.findById({ _id: userId });

            if (userInstance === null) {
                throw new Error("User not found");
            }

            console.log(`User ${userId} connected via SSE for flow: ${slug}, type: ${flowType}`);
            sseBus.register(userId, res);
            this.processAIFlowConnection(userInstance, res);
        } catch (error) {
            console.error("SSE connection error in AI service:", error);
            this.sendError(res, "Internal server error");
        }
    };

    private sendError(res: Response, message: string): void {
        const errorPayload = {
            type: "error",
            message: message,
        };

        res.write(`data: ${JSON.stringify(errorPayload)}\n\n`);
        res.end();
    }

    writeToSse = (res: Response, payload: Record<string, unknown>): void => {
        res.write(`data: ${JSON.stringify(payload)}\n\n`);
    };

    sendInitialGreeting = async (userInstance: IUser, res: Response): Promise<void> => {
        try {
            const {
                onboarding_data: { preferred_name },
                preferred_language,
            } = userInstance as IUser;

            const greeetingMessage: AIGreetingMessage = {
                id: getUuid(),
                type: "ai_message",
                text: getAIGreetingMessage(preferred_name || "there", preferred_language),
                timestamp: Date.now(),
                response: {},
                nodeType: FlowNodeEnum.QUESTION_FREE_TEXT,
            };
            this.writeToSse(res, greeetingMessage);
        } catch (error) {
            throw error;
        }
    };

    processAIFlowConnection = async (userInstance: IUser, res: Response): Promise<boolean> => {
        await this.sendInitialGreeting(userInstance, res);
        return true;
    };

    saveResponse = async (
        userId: string,
        freeText: string,
        sessionId: string,
        conversationId: ObjectId,
        model: string,
        turn: TChatTurn = {},
    ) => {
        try {
            const userInstance: IUser | null = await this.userService.findById({ _id: userId });
            if (!userInstance) {
                throw new Error("User not found");
            }
            if (!freeText && !turn.attachments?.length) {
                throw new Error("Free text is required");
            }
            await this.processChatbotResponse(
                userInstance,
                freeText,
                sessionId,
                conversationId,
                model,
                turn,
            );
        } catch (error) {
            if (!(error instanceof HandledTurnError)) {
                // Failed before her message was even recorded: still give the unit
                // back and tell the app, or its spinner waits forever.
                await this.failTurn(userId, null, turn, { sessionId, conversationId });
            }
            log.error({ err: error, userId }, "Chatbot turn failed");
            throw error;
        }
    };

    createMessage = async (payload: Partial<IMessage>): Promise<IMessage> => {
        const messageInstance = await this.messageService.create(payload);
        return messageInstance;
    };
    getUserConnection = (userId: Types.ObjectId): Response | undefined => {
        return sseBus.getLocal(userId.toString());
    };

    /**
     * Give back the AI_CHAT unit her turn spent, at most once however many paths ask
     * (a refusal the chatbot reported and an error afterwards, say). Returns her quota
     * as it now stands, for the app's "2 of 3 left" line.
     */
    refundTurn = async (userId: string, userMessageId: unknown | null): Promise<TQuota | null> => {
        try {
            if (userMessageId) {
                const claimed = await messageModel.findOneAndUpdate(
                    { _id: userMessageId, quotaRefunded: { $ne: true } },
                    { $set: { quotaRefunded: true } },
                );
                if (!claimed)
                    return await entitlementService.peekQuota(userId, ECapability.AI_CHAT);
            }
            await entitlementService.refundQuota(userId, ECapability.AI_CHAT);
            return await entitlementService.peekQuota(userId, ECapability.AI_CHAT);
        } catch (err) {
            log.error({ err, userId }, "Refunding AI chat quota failed");
            return null;
        }
    };

    /**
     * Her turn could not be answered. Refund it, drop any files it carried, leave a
     * record the app can poll for, and tell the app now so it can offer a retry.
     */
    failTurn = async (
        userId: string,
        userMessageId: unknown | null,
        turn: TChatTurn,
        context: { sessionId?: string; conversationId?: unknown },
    ): Promise<void> => {
        const attachments = turn.attachments ?? [];
        const code: AIErrorEvent["code"] = attachments.length
            ? "ATTACHMENT_PROCESSING_FAILED"
            : "AI_UNAVAILABLE";
        try {
            const quota = await this.refundTurn(userId, userMessageId);
            await chatAttachmentService
                .markOutcome(attachments, { status: EAttachmentStatus.FAILED })
                .catch((err) => log.error({ err, userId }, "Marking attachments failed"));
            if (turn.clientMessageId && context.conversationId) {
                await this.createMessage({
                    conversationId: context.conversationId as Schema.Types.ObjectId,
                    userId,
                    role: MessageRoleEnum.ASSITANT,
                    type: MessageTypeEnum.SYSTEM,
                    text: "",
                    rich: null,
                    attachments: null,
                    ai: null,
                    guided: null,
                    replyTo: turn.clientMessageId,
                    sessionId: context.sessionId ?? null,
                    errorCode: code,
                }).catch((err) => log.error({ err, userId }, "Saving failed-turn record failed"));
            }
            const event: AIErrorEvent = {
                type: "ai_error",
                replyTo: turn.clientMessageId ?? null,
                code,
                timestamp: Date.now(),
                quota,
            };
            await sseBus.publish(userId, event);
        } catch (err) {
            log.error({ err, userId }, "Failing chatbot turn failed");
        }
    };

    /**
     * The reply to one of her turns, for the app's fallback when the stream did not
     * deliver it. `pending` while the chatbot is still working on it.
     */
    getReply = async (
        userId: string,
        clientMessageId: string,
    ): Promise<
        | { status: "not_found" }
        | { status: "pending" }
        | { status: "ready"; payload: AILLMResponse | AIErrorEvent }
    > => {
        const turn = await messageModel
            .findOne({ userId, clientMessageId, role: MessageRoleEnum.USER })
            .select("_id")
            .lean();
        if (!turn) return { status: "not_found" };
        const reply = await messageModel
            .findOne({ userId, replyTo: clientMessageId, role: MessageRoleEnum.ASSITANT })
            .lean();
        if (!reply) return { status: "pending" };
        if (reply.errorCode) {
            return {
                status: "ready",
                payload: {
                    type: "ai_error",
                    replyTo: clientMessageId,
                    code: reply.errorCode as AIErrorEvent["code"],
                    timestamp: new Date(reply.createdAt).getTime(),
                    quota: await entitlementService.peekQuota(userId, ECapability.AI_CHAT),
                },
            };
        }
        return {
            status: "ready",
            payload: {
                ...(reply.sessionId ? { sessionId: reply.sessionId } : {}),
                conversationId: reply.conversationId as unknown as ObjectId,
                id: String(reply._id),
                type: "ai_message",
                text: reply.text,
                timestamp: new Date(reply.createdAt).getTime(),
                response: {},
                nodeType: FlowNodeEnum.QUESTION_FREE_TEXT,
                suggestedExperts: reply.suggestedExperts ?? [],
                pendingLogs: reply.pendingLogs ?? [],
                replyTo: clientMessageId,
                attachment: reply.attachmentVerdict
                    ? {
                          verdict: reply.attachmentVerdict.verdict,
                          reasonCode: reply.attachmentVerdict.reasonCode ?? null,
                      }
                    : null,
            },
        };
    };

    processChatbotResponse = async (
        userInstance: IUser,
        message: string,
        sessionId: string,
        conversationId: ObjectId,
        model: string,
        turn: TChatTurn = {},
    ): Promise<{ success: boolean; message: string }> => {
        const userId = String(userInstance._id);
        const attachments = turn.attachments ?? [];
        const clientMessageId = turn.clientMessageId ?? null;
        const text = (message ?? "").trim();
        let userMessageId: unknown | null = null;
        try {
            if (!conversationId) {
                conversationId = await this.createChatbotConversation(userInstance);
            }
            if (!sessionId) {
                sessionId = getUuid();
            }
            try {
                const userMessage = await this.createMessage({
                    conversationId: conversationId,
                    userId: userInstance._id as unknown as string,
                    role: MessageRoleEnum.USER,
                    type: MessageTypeEnum.AI,
                    text,
                    rich: null,
                    attachments: attachments.length
                        ? attachments.map((a) => chatAttachmentService.toMessageAttachment(a))
                        : null,
                    ai: null,
                    guided: null,
                    clientMessageId,
                });
                userMessageId = userMessage._id;
            } catch (err: any) {
                if (err?.code === 11000) {
                    // The same turn arrived twice at once; the first one is being
                    // answered. Give back what this copy spent and stop.
                    await this.refundTurn(userId, null);
                    return { success: true, message: "Duplicate chatbot turn ignored" };
                }
                throw err;
            }

            // A typed "yes" / "haan" answers the "Save this log?" card on her last
            // reply. It is not a question, so it never reaches the chatbot. Never on a
            // turn with files: "yes, see attached" is a question about the file.
            const confirmReply = attachments.length ? null : parseConfirmReply(text);
            if (confirmReply) {
                const answered = await this.chatLogProposalService.answerLatest(
                    userId,
                    String(conversationId),
                    confirmReply === "yes",
                );
                if (answered) {
                    const replyText = confirmationReply(
                        text,
                        answered.saved,
                        answered.dismissed,
                        answered.reminder,
                    );
                    const replyInstance = await this.createMessage({
                        conversationId: conversationId,
                        userId: userInstance._id as unknown as string,
                        role: MessageRoleEnum.ASSITANT,
                        type: MessageTypeEnum.AI,
                        text: replyText,
                        rich: null,
                        attachments: null,
                        ai: null,
                        guided: null,
                        replyTo: clientMessageId,
                        sessionId,
                    });
                    await conversationModel.findByIdAndUpdate(conversationId, {
                        lastMessageAt: new Date(),
                    });
                    await sseBus.publish(userId, {
                        sessionId,
                        conversationId,
                        id: replyInstance._id as unknown as string,
                        type: "ai_message",
                        text: replyText,
                        timestamp: Date.now(),
                        response: { intent: "LOG_CONFIRMATION" },
                        nodeType: FlowNodeEnum.QUESTION_FREE_TEXT,
                        updatedPendingLogs: {
                            messageId: answered.messageId,
                            pendingLogs: answered.pendingLogs,
                        },
                        replyTo: clientMessageId,
                    } satisfies AILLMResponse);
                    return {
                        success: true,
                        message: "Chatbot message processed successfully",
                    };
                }
            }

            const llmResponse = await this.llmService.sendUserQuery(
                userInstance,
                text,
                sessionId,
                model,
                {
                    attachments: attachments.map((a) => chatAttachmentService.toChatbotRef(a)),
                    lang: toChatbotLang(turn.lang ?? userInstance.preferred_language),
                },
            );

            // What the chatbot decided about her files. Anything it did not accept as
            // a mother/baby health document is deleted now, not kept for 90 days.
            const verdict = attachments.length
                ? ((llmResponse.attachment as Record<string, string | null> | null) ?? null)
                : null;
            if (attachments.length) {
                await chatAttachmentService.markOutcome(attachments, {
                    status:
                        verdict?.verdict === ACCEPTED_VERDICT
                            ? EAttachmentStatus.ANALYZED
                            : EAttachmentStatus.REJECTED,
                    verdict: {
                        code: verdict?.verdict ?? null,
                        category: verdict?.category ?? null,
                        subject: verdict?.subject ?? null,
                    },
                    conversationId,
                    messageId: userMessageId,
                });
            }
            // Refused or unreadable files do not cost her a question.
            const quota =
                llmResponse.quota_refund === true
                    ? await this.refundTurn(userId, userMessageId)
                    : null;

            const suggestedExperts = await this.resolveSuggestedExperts(
                userId,
                llmResponse.suggested_experts,
            );
            // Logs the chatbot read out of her message, validated here before they
            // become a confirm card. Nothing is saved until she says yes.
            const pendingLogs = await this.chatLogProposalService.prepare(
                userId,
                llmResponse.proposed_logs,
            );
            const attachmentVerdict = verdict
                ? {
                      verdict: String(verdict.verdict ?? "UNKNOWN"),
                      category: verdict.category ?? null,
                      subject: verdict.subject ?? null,
                      reasonCode: verdict.reason_code ?? null,
                  }
                : null;
            const aiMessageInstance = await this.createMessage({
                conversationId: conversationId,
                userId: userInstance._id as unknown as string,
                role: MessageRoleEnum.ASSITANT,
                type: MessageTypeEnum.AI,
                text: llmResponse.answer as string,
                rich: null,
                attachments: null,
                ai: null,
                guided: null,
                suggestedExperts,
                pendingLogs,
                replyTo: clientMessageId,
                sessionId,
                attachmentVerdict,
            });
            await conversationModel.findByIdAndUpdate(conversationId, {
                lastMessageAt: new Date(),
            });
            const aiLlmResponse: AILLMResponse = {
                sessionId: sessionId,
                conversationId: conversationId,
                id: aiMessageInstance._id as unknown as string,
                type: "ai_message",
                text: llmResponse.answer as string,
                timestamp: Date.now(),
                // A whitelist, not the chatbot's whole response: that carries the
                // final prompt (her profile, retrieved context) and has no business
                // on the phone.
                response: {
                    intent: llmResponse.intent ?? null,
                    escalation_banner: llmResponse.escalation_banner ?? null,
                    products: llmResponse.products ?? [],
                },
                nodeType: FlowNodeEnum.QUESTION_FREE_TEXT,
                suggestedExperts,
                pendingLogs,
                replyTo: clientMessageId,
                attachment: attachmentVerdict
                    ? {
                          verdict: attachmentVerdict.verdict,
                          reasonCode: attachmentVerdict.reasonCode,
                      }
                    : null,
                quota,
            };

            await sseBus.publish(userId, aiLlmResponse);
            return {
                success: true,
                message: "Chatbot message processed successfully",
            };
        } catch (error) {
            log.error({ err: error, userId }, "Error handling chatbot message");
            await this.failTurn(userId, userMessageId, turn, { sessionId, conversationId });
            throw new HandledTurnError(error);
        }
    };

    private async createChatbotConversation(userInstance: IUser): Promise<Schema.Types.ObjectId> {
        console.log(`Creating new chatbot conversation for user ${userInstance._id}`);
        const conversation = await new conversationModel({
            userId: userInstance._id,
            title: "Chat with AI Assistant",
            chatMode: "AI_ONLY",
            lastMessageAt: new Date(),
            meta: {
                channel: "App",
                tags: ["chatbot"],
            },
        }).save();

        return conversation._id;
    }

    private async sendSilentPush(userId: string, messagePayload: AILLMResponse): Promise<void> {
        try {
            const user = await this.userService.findOne({ _id: userId });
            if (!user || !user.FCM_token) {
                console.log(`No FCM token for user ${userId}`);
                return;
            }

            const message = {
                data: {
                    type: "NEW_CHATBOT_RESPONSE",
                    questionData: JSON.stringify(messagePayload),
                },
                token: user.FCM_token,
                apns: {
                    headers: {
                        "apns-push-type": "background",
                        "apns-priority": "5",
                    },
                    payload: {
                        aps: {
                            "content-available": 1,
                        },
                    },
                },
                android: {
                    priority: "high" as const,
                },
            };

            await admin!.messaging().send(message);
            console.log(`Sent silent push for user ${userId}`);
        } catch (error) {
            console.error("Error sending silent push:", error);
        }
    }
}

export default ChatFlowAIService;
