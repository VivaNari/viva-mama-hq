import { Schema } from "mongoose";

import { generalSchemaOptions } from "../../constants/model";
import { ACCEPTED_ATTACHMENT_MIME_TYPES } from "../../types/chat-attachment.types";
import { AttachmentTypeEnum } from "../../types/chat.types";
import {
    EHealthRecordCategory,
    EHealthRecordStatus,
    ERecordSubject,
    EScanType,
    IHealthRecord,
    IHealthRecordFile,
} from "../../types/health-record.types";

const fileSchema = new Schema<IHealthRecordFile>(
    {
        // Per picked file, so a retried page upload is not stored twice.
        clientUploadId: { type: String, required: true },
        objectName: { type: String, required: true },
        kind: {
            type: String,
            enum: [AttachmentTypeEnum.IMAGE, AttachmentTypeEnum.PDF],
            required: true,
        },
        mimeType: { type: String, enum: ACCEPTED_ATTACHMENT_MIME_TYPES, required: true },
        sizeBytes: { type: Number, required: true },
        sha256: { type: String, required: true },
        width: { type: Number, default: null },
        height: { type: Number, default: null },
        pageCount: { type: Number, default: null },
        // PDFs only, truncated, as for chat attachments.
        originalName: { type: String, default: null, maxlength: 80 },
    },
    { _id: false },
);

/** Her saved health records. See IHealthRecord. */
const healthRecordSchema = new Schema<IHealthRecord>(
    {
        userId: { type: Schema.Types.ObjectId, ref: "users", required: true },
        // Generated by the app per record, so a retried "create" returns the same draft.
        clientUploadId: { type: String, required: true },
        category: { type: String, enum: Object.values(EHealthRecordCategory), required: true },
        scanType: { type: String, enum: [...Object.values(EScanType), null], default: null },
        subject: {
            type: new Schema(
                {
                    type: { type: String, enum: Object.values(ERecordSubject), required: true },
                    childId: { type: Schema.Types.ObjectId, default: null },
                },
                { _id: false },
            ),
            required: true,
        },
        files: { type: [fileSchema], default: [] },
        bucket: { type: String, required: true },
        status: {
            type: String,
            enum: Object.values(EHealthRecordStatus),
            default: EHealthRecordStatus.DRAFT,
        },
        verdict: {
            type: new Schema(
                { code: String, reasonCode: String, documentType: String },
                { _id: false },
            ),
            default: null,
        },
        message: { type: String, default: null },
        title: { type: String, default: null, maxlength: 200 },
        recordDate: { type: Date, required: true },
        summary: {
            type: new Schema(
                {
                    markdown: String,
                    analysis: { type: Schema.Types.Mixed, default: null },
                    digest: String,
                    severity: { type: String, enum: ["NONE", "MEDIUM", "HIGH"] },
                    criticalMatches: { type: [String], default: [] },
                    lang: String,
                    generatedAt: Date,
                },
                { _id: false },
            ),
            default: null,
        },
        lang: { type: String, enum: ["en", "hi"], default: "en" },
        submittedAt: { type: Date, default: null },
        attempts: { type: Number, default: 0 },
        quotaRefunded: { type: Boolean, default: false },
        deletedAt: { type: Date, default: null },
        purgeAt: { type: Date, default: null },
    },
    generalSchemaOptions,
);

healthRecordSchema.index({ userId: 1, clientUploadId: 1 }, { unique: true });
// The list: her live records, newest report first.
healthRecordSchema.index({ userId: 1, deletedAt: 1, recordDate: -1, _id: -1 });
// The janitor: stale drafts and stuck PROCESSING records.
healthRecordSchema.index({ status: 1, updatedAt: 1 });
healthRecordSchema.index({ purgeAt: 1 }, { expireAfterSeconds: 0 });

export default healthRecordSchema;
